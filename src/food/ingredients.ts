const STEMS = DICT.flatMap(([name, stems]) => stems.map((s) => [s, name] as const)).sort((a, b) => b[0].length - a[0].length);

const clean = (s: string) =>
  s
    .replace(BULLET, '')
    .replace(/\s+/g, ' ')
    .replace(/[.;]+$/, '')
    .trim()
    .slice(0, 80);

/** Інгредієнти з опису: список, якщо він є, інакше знайомі продукти з тексту */
export function extractIngredients(text: string): string[] {
  const t = (text || '').trim();
  if (!t) return [];
  const out: string[] = [];
  const add = (s: string) => {
    const v = clean(s);
    if (v && v.length > 1 && !out.some((x) => x.toLowerCase() === v.toLowerCase())) out.push(v);
  };

  const lines = t.split(/\r?\n/);
  let inList = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (!line) {
      inList = false;
      continue;
    }
    const head = line.match(HEAD);
    if (head) {
      const rest = line.slice((head.index ?? 0) + head[0].length);
      rest.split(/[,;]/).forEach(add);
      inList = !rest.trim(); // список у наступних рядках — лише якщо після двокрапки порожньо
      continue;
    }
    if (BULLET.test(line) || (UNIT.test(line) && line.length <= 80) || (inList && line.length <= 60)) add(line);
  }
  if (out.length) return out;

  // Немає списку — шукаємо знайомі продукти в тексті
  const words = t.toLowerCase().replace(/[’'`]/g, 'ʼ').match(/[\p{L}ʼ]+/gu) ?? [];
  for (const w of words) {
    const hit = STEMS.find(([s]) => w.startsWith(s) && w.length - s.length <= 3);
    if (hit && !out.includes(hit[1])) out.push(hit[1]);
  }
  return out;
}
