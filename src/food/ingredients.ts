// Інгредієнти з опису страви (16.11): без ШІ, за простими правилами.
// 1) Якщо в описі є список (рядки з «-», «•», «1.», з кількістю «200 г», або після «інгредієнти:» / «склад:») — беремо його.
// 2) Інакше шукаємо в тексті знайомі продукти зі словника (з урахуванням відмінків: «сиру», «яйцями», «борошна»).

const UNIT = /\d+([.,]\d+)?\s*((г|гр|кг|мл|л|шт)(?!\p{L})|ст\.?\s*л|ч\.?\s*л|склян|пуч|зубч|дрібк|щіпк)/iu;
const BULLET = /^\s*([-–—•*·]|\d+[.)])\s+/;
const HEAD = /(інгредієнти|інгридієнти|склад|потрібно|знадобиться|продукти)\s*:\s*/i;

// [назва, основи слів]; основа + до 3 літер закінчення («сир» → «сиру», «сиром», але не «сирники»)
